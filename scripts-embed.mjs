// Embeds the Vite build (dist/) into the Worker bundle so deploy is a single script upload.
// Text files are inlined as strings; binary files (images, audio, fonts) as base64 (`b64: true`).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(p); } };
walk('dist');
const types = { html: 'text/html; charset=utf-8', js: 'text/javascript', css: 'text/css', svg: 'image/svg+xml', json: 'application/json', txt: 'text/plain', webmanifest: 'application/manifest+json' };
const bin = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', webp: 'image/webp', ico: 'image/x-icon', mp3: 'audio/mpeg', ogg: 'audio/ogg', woff2: 'font/woff2' };
const MAX = 2 * 1024 * 1024;
let out = '// generated by scripts-embed.mjs\n';
const rows = [];
let binBytes = 0;
for (const f of files) {
  const ext = f.split('.').pop().toLowerCase();
  const path = JSON.stringify('/' + relative('dist', f).split('\\').join('/'));
  if (types[ext]) {
    rows.push(`  ${path}: { body: ${JSON.stringify(readFileSync(f, 'utf8'))}, type: ${JSON.stringify(types[ext])} },`);
  } else if (bin[ext]) {
    const buf = readFileSync(f);
    if (buf.length > MAX) { console.warn(`skipping ${f}: ${(buf.length / 1048576).toFixed(1)} MB > 2 MB`); continue; }
    binBytes += buf.length;
    rows.push(`  ${path}: { body: ${JSON.stringify(buf.toString('base64'))}, type: ${JSON.stringify(bin[ext])}, b64: true },`);
  }
}
out += `export const STATIC: Record<string, { body: string; type: string; b64?: boolean }> = {\n${rows.join('\n')}\n};\n`;
writeFileSync('worker/static.gen.ts', out);
console.log(`embedded ${rows.length} files (${(binBytes / 1024).toFixed(0)} KB binary)`);
// Free-plan Workers are capped at ~3 MB gzipped; base64 audio/images barely compress.
if (binBytes > 2.2 * 1024 * 1024) console.warn(`warning: ${(binBytes / 1048576).toFixed(1)} MB of binary assets embedded; the Worker may exceed the 3 MB free-plan limit (check: npx wrangler deploy --dry-run --outdir /tmp/nah-bundle)`);
